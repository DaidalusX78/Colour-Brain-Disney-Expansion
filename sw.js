const CACHE_NAME = 'colourbrain-disney-v1.11.8';
const CORE_ASSETS = [
  './',
  './index.html',
  './questions.js',
  './manifest.json',
  './assets/silhouettes/mickey_silhouette.svg',
  './assets/logos/disney_channel.svg',
  './assets/logos/walt_disney_animation_studios.svg',
  './assets/logos/pixar.svg',
  './assets/logos/lucasfilm.svg',
  './assets/logos/marvel_studios.svg'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(CORE_ASSETS)).catch(() => {})
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  event.respondWith(
    caches.match(event.request).then((cachedResponse) => {
      const fetchPromise = fetch(event.request)
        .then((networkResponse) => {
          if (networkResponse && networkResponse.status === 200) {
            const responseClone = networkResponse.clone();
            caches.open(CACHE_NAME).then((cache) => {
              cache.put(event.request, responseClone);
            });
          }
          return networkResponse;
        })
        .catch(() => cachedResponse);
      return cachedResponse || fetchPromise;
    })
  );
});

